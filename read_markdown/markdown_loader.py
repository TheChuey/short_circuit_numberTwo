"""
read_markdown/markdown_loader.py
================================

THE READ SIDE OF THE MARKDOWN PIPELINE
--------------------------------------

WHAT THIS MODULE AFFECTS:
    Reads  read_markdown/app_blueprint.md    ->  config/agent.json    (name, default_model, skills,
                                                                       role, user, job, composed system_prompt)
    Reads  read_markdown/chatbot_prompt.md   ->  config/chat_bot.json (same shape as agent.json;
                                                                       built alongside it so the chat
                                                                       path can be switched later)
    Reads  write_markdown/tools.md           ->  config/tools.json    (the tools -> GET /api/tools)
    Writes (only if a blueprint is missing) the default .md templates above
    Affects POST /api/chat (the agent's identity) and GET /api/tools (the toolbox).

It is written as a CLASS (MarkdownLoader) so the same parsing logic can serve
both blueprints: each blueprint gets its own MarkdownLoader instance with its
own file paths, default template and output files.

Why a markdown file?
    A markdown file is easy for a human to read and edit: headings and bullet
    points are self-documenting, and git diffs are clean. The JSON files are
    just the machine-readable output of that file.

    models.json is deliberately NOT produced here -- the model list is dynamic
    (it changes whenever Ollama / LM Studio models change) and is owned by
    write_markdown/app_config.py (AppConfig), which scans the LLMs at startup.

    skills.json is also NOT produced here anymore -- it is generated from the
    SKILL_REGISTRY in app/tools/tools.py by AppConfig (the skills catalog /
    test point), not from the blueprint.

When does this run?
    server.py calls load_all() on startup (inside a FastAPI lifespan event),
    so any edit to either blueprint takes effect on the next server restart.
    You can also run this file directly:  python read_markdown/markdown_loader.py

If a blueprint is missing, MarkdownLoader.ensure() recreates it from the
default template embedded below, then parsing proceeds normally.
"""

