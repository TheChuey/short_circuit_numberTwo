class MarkdownLoader:
    """Load one markdown blueprint and regenerate its JSON output file(s).

    A single instance owns ONE blueprint and the output files it produces.
    Three instances are used at module level (see below): one for the agent
    blueprint (agent.json), one for the chatbot prompt (chat_bot.json) and
    one for the tools blueprint (tools.json).
    """

    def __init__(self, blueprint_path, default_blueprint, output_paths=None):
        """Store the blueprint location, its fallback template and its outputs.

        Args:
            blueprint_path:     path to the source markdown file.
            default_blueprint:  template text written if the markdown is missing.
            output_paths:       dict mapping kind ('agent'/'tools')
                                to the output JSON file that kind is written to.
        """
        self.blueprint_path = Path(blueprint_path)
        self.default_blueprint = default_blueprint
        self.output_paths = output_paths or {}

    # ------------------------------------------------------------------
    # PARSING HELPERS (pure functions -> instance methods)
    # ------------------------------------------------------------------

    def _parse_key_value(self, text: str) -> dict:
        """Turn a block of '- key: value' bullet lines into a dictionary.

        Example input:
            - name: Save
            - icon: 💾
            - enabled: true

        Example output:
            {"name": "Save", "icon": "💾", "enabled": true}
        """
        data = {}
        for line in text.splitlines():
            # Match "- key: value" where key is letters/digits/underscore.
            match = re.match(r"^\s*-\s*([A-Za-z0-9_]+)\s*:\s*(.*)$", line)
            if match:
                value = match.group(2).strip()
                # Coerce "true"/"false" strings to real booleans so the frontend
                # gets JSON booleans instead of the strings "true"/"false".
                if value.lower() == "true":
                    value = True
                elif value.lower() == "false":
                    value = False
                data[match.group(1).strip()] = value
        return data

    def _parse_item_blocks(self, text: str) -> list:
        """Parse a '### <id>' block section (used for skills and tools).

        Each '### <id>' heading starts a new item; the '- key: value' lines
        under it become that item's fields, and the heading text becomes 'id'.

        Example input:
            ### save
            - name: Save
            - icon: 💾

        Example output:
            [{"id": "save", "name": "Save", "icon": "💾"}]
        """
        items = []
        current_id = None
        buffer = []
        for line in text.splitlines(keepends=True):
            # A level-3 heading like "### save" starts a new item.
            match = re.match(r"^\s*#{3,}\s+(.+?)\s*$", line)
            if match:
                if current_id is not None:  # flush the previous item
                    items.append({"id": current_id, **self._parse_key_value("".join(buffer))})
                current_id, buffer = match.group(1).strip(), []
            else:
                buffer.append(line)
        if current_id is not None:  # flush the last item
            items.append({"id": current_id, **self._parse_key_value("".join(buffer))})
        return items

    def _split_sections(self, text: str) -> dict:
        """Split the markdown into top-level '## <name>' sections.

        Everything after a '## name' heading (until the next '## name') is
        stored under that lower-cased name. Level-3 '###' headings do NOT
        split sections (they belong to the section that contains them).
        """
        sections = {}
        current = None
        buffer = []
        for line in text.splitlines(keepends=True):
            # Match exactly two hashes + space, so '### ' (items) is NOT a section.
            match = re.match(r"^\s*##\s+(.+?)\s*$", line)
            if match:
                if current is not None:  # flush the previous section
                    sections[current] = "".join(buffer)
                current, buffer = match.group(1).strip().lower(), []
            elif current is not None:
                buffer.append(line)
        if current is not None:  # flush the last section
            sections[current] = "".join(buffer)
        return sections

    def _clean_body(self, text: str) -> str:
        """Trim blank lines and '---' separators from the edges of a section body."""
        lines = text.splitlines()
        # Drop empty / separator lines from the top...
        while lines and (not lines[0].strip() or lines[0].strip() in ("---", "***")):
            lines.pop(0)
        # ...and from the bottom.
        while lines and (not lines[-1].strip() or lines[-1].strip() in ("---", "***")):
            lines.pop()
        return "\n".join(lines).strip("\n")

    # ------------------------------------------------------------------
    # FILE HELPERS
    # ------------------------------------------------------------------

    def ensure(self) -> Path:
        """Create the blueprint from its default template if it is missing.

        Satisfies the "if no markdown exists, make one" requirement: the app
        never crashes on a missing blueprint, it just seeds a default one.
        Returns the blueprint file path.
        """
        if not self.blueprint_path.exists():
            self.blueprint_path.parent.mkdir(parents=True, exist_ok=True)
            self.blueprint_path.write_text(self.default_blueprint, encoding="utf-8")
            print(f"[markdown_loader] created default blueprint at {self.blueprint_path}")
        return self.blueprint_path

    def write_json(self, path: Path, data: dict) -> None:
        """Write a dict to a JSON file (pretty-printed, UTF-8)."""
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            json.dumps(data, indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )

    # ------------------------------------------------------------------
    # SECTION BUILDERS (markdown sections -> JSON-ready structures)
    # ------------------------------------------------------------------

    def build_agent(self, sections: dict) -> dict:
        """Build the agent.json content from the 'agent' section + 'role'/'user'/'job'.

        The three free-text sections describe the agent (role), who it talks to
        (user) and what it does (job). Each is stored raw so the JSON is
        transparent, AND they are composed into the 'system_prompt' that the
        LLM actually receives.
        """
        fields = self._parse_key_value(sections.get("agent", ""))
        # The 'skills' value is a comma-separated list -> split into a real list.
        skills = [s.strip() for s in fields.get("skills", "").split(",") if s.strip()]
        role = self._clean_body(sections.get("role", ""))
        user = self._clean_body(sections.get("user", ""))
        job = self._clean_body(sections.get("job", ""))
        return {
            "name": fields.get("name", "Agent"),
            "default_model": fields.get("default_model", ""),
            "skills": skills,
            "role": role,
            "user": user,
            "job": job,
            "system_prompt": self._compose_system_prompt(role, user, job),
        }

    @staticmethod
    def _compose_system_prompt(role: str, user: str, job: str) -> str:
        """Assemble the final system prompt from the role/user/job sections.

        Each present section is prefixed with a header line so the LLM can tell
        WHO it is, WHO it talks to, and WHAT it should do. Empty sections are
        simply skipped.
        """
        parts = []
        if role:
            parts.append(f"ROLE\n{role}")
        if user:
            parts.append(f"ABOUT THE USER\n{user}")
        if job:
            parts.append(f"JOB DESCRIPTION\n{job}")
        return "\n\n".join(parts)

    def build_tools(self, sections: dict) -> list:
        """Build the tools list from the 'tools' section ('### <id>' blocks)."""
        return self._parse_item_blocks(sections.get("tools", ""))

    # ------------------------------------------------------------------
    # MAIN ENTRY POINT
    # ------------------------------------------------------------------

    def load(self, kinds=None) -> dict:
        """Read the blueprint and regenerate the requested JSON output(s).

        Args:
            kinds: list of which configs to build + write, e.g. ["agent", "skills"].
                   Defaults to every kind this instance has an output for.

        Returns:
            dict mapping each requested kind to its parsed (JSON-ready) value.
        """
        # Default: load every kind this instance is configured to output.
        if kinds is None:
            kinds = list(self.output_paths.keys())

        self.ensure()  # 1. create the markdown if it's missing

        # 2. Read the whole blueprint and split it into its '## ' sections.
        sections = self._split_sections(self.blueprint_path.read_text(encoding="utf-8"))

        # 3. Build each requested kind and write it to its output file.
        result = {}
        for kind in kinds:
            if kind == "agent":
                data = self.build_agent(sections)
            elif kind == "chat_bot":
                data = self.build_agent(sections)
            elif kind == "tools":
                data = {"tools": self.build_tools(sections)}
            else:
                raise ValueError(f"unknown config kind: {kind!r}")

            result[kind] = data
            if kind in self.output_paths:  # persist (some kinds may not map to a file)
                self.write_json(self.output_paths[kind], data)
                print(f"[markdown_loader] regenerated {self.output_paths[kind].name} from {self.blueprint_path.name}")

        return result


# --------------------------------------------------------------------------
# MODULE-LEVEL INSTANCES + CONVENIENCE API (kept for server.py compatibility)
# --------------------------------------------------------------------------

# Loader for the agent blueprint -> agent.json.
# (skills.json is NOT built here - AppConfig generates it from tools.py.)
AGENT_LOADER = MarkdownLoader(
    blueprint_path=BLUEPRINT_FILE,
    default_blueprint=DEFAULT_BLUEPRINT,
    output_paths={"agent": AGENT_FILE},
)

# Loader for the chatbot prompt blueprint -> chat_bot.json. Same agent builder
# as AGENT_LOADER (identical JSON shape), but fed from its own markdown file.
CHATBOT_LOADER = MarkdownLoader(
    blueprint_path=CHATBOT_BLUEPRINT_FILE,
    default_blueprint=DEFAULT_CHATBOT_BLUEPRINT,
    output_paths={"chat_bot": CHATBOT_FILE},
)

# Loader for the UI tool-button blueprint -> tools.json.
TOOLS_LOADER = MarkdownLoader(
    blueprint_path=TOOLS_BLUEPRINT_FILE,
    default_blueprint=DEFAULT_TOOLS_BLUEPRINT,
    output_paths={"tools": TOOLS_FILE},
)


def load_all() -> dict:
    """Regenerate every JSON config from both blueprints.

    Steps:
        1. AGENT_LOADER.load(["agent"])      -> agent.json
        2. CHATBOT_LOADER.load(["chat_bot"]) -> chat_bot.json
        3. TOOLS_LOADER.load(["tools"])      -> tools.json
        4. return everything (also useful for debugging / tests)

    Call this from server.py's startup event so config is always fresh.
    (models.json + skills.json are generated by AppConfig, not here.)
    """
    result = {}
    result.update(AGENT_LOADER.load(kinds=["agent"]))
    result.update(CHATBOT_LOADER.load(kinds=["chat_bot"]))
    result.update(TOOLS_LOADER.load(kinds=["tools"]))
    return result


# --------------------------------------------------------------------------
# STANDALONE RUN
# --------------------------------------------------------------------------
if __name__ == "__main__":
    # Running `python read_markdown/markdown_loader.py` regenerates the JSON files
    # and prints what was parsed (handy for eyeballing the result).
    # Force UTF-8 output so emoji (e.g. tool icons like 💾) survive the print
    # on Windows consoles, which default to the cp1252 codepage.
    sys.stdout.reconfigure(encoding="utf-8")
    result = load_all()
    print(json.dumps(result, indent=2, ensure_ascii=False))
